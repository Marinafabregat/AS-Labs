@router.post("/{item_id}/edit")
async def edit_item(
    request: Request,
    item_id: int,
    title: str = Form(...),
    description: str = Form(...),
    price: float = Form(...),
    category_id: int = Form(...),
    image: Optional[UploadFile] = File(None),
    current_user: User = Depends(get_current_active_user),
    session: Session = Depends(get_session),
):
    item = load_item_or_404(session, item_id)

    # Authorization is checked again on POST, not only on the GET form.
    enforce(current_user, "update", "item", item_attrs(item))

    already_bought = session.exec(
        select(Purchase).where(Purchase.item_id == item_id)
    ).first()

    if already_bought:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Cannot edit a product that has already been sold.",
        )

    categories = session.exec(select(Category)).all()

    try:
        validate_item_fields(
            title,
            description,
            price,
            category_id,
            session,
        )
    except HTTPException as exc:
        return render_item_form_error(
            request,
            "edit_item.html",
            {
                "user": current_user,
                "item": item,
                "categories": categories,
            },
            str(exc.detail),
        )

    new_filename = None

    if image and image.filename:
        try:
            contents = await read_upload_limited(image)
            new_filename = validate_and_save_image(
                contents,
                image.filename,
            )
        except ValueError as exc:
            return render_item_form_error(
                request,
                "edit_item.html",
                {
                    "user": current_user,
                    "item": item,
                    "categories": categories,
                },
                str(exc),
            )
        finally:
            await image.close()

        # Store the new image first, delete the old one only after the DB commit succeeds
        old_image = item.image_filename
        item.image_filename = encode_and_store_image(img)
    else:
        old_image = None

    item.title = title
    item.description = description
    item.price = price
    item.category_id = category_id

    if new_filename:
        item.image_filename = new_filename

    try:
        session.add(item)
        session.commit()
        session.refresh(item)
    except Exception:
        session.rollback()

        if new_filename:
            remove_uploaded_image(new_filename)

        raise

    # The old image is removed only after the database commit succeeds.
    if new_filename and old_filename != new_filename:
        remove_uploaded_image(old_filename)

    if old_image and old_image != item.image_filename:
        delete_image(old_image)

    return RedirectResponse(
        url=f"/items/{item.id}",
        status_code=status.HTTP_302_FOUND,
    )


