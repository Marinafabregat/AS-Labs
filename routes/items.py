# All routes inside this document will start with '/items'
router = APIRouter(prefix="/items", tags=["Items"])

# Security rules for file uploads
MAX_FILE_SIZE = 5 * 1024 * 1024  # 5 MB
ALLOWED_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp"}
ALLOWED_FORMATS = {"JPEG", "PNG", "WEBP"}
FORMAT_TO_EXT = {"JPEG": ".jpg", "PNG": ".png", "WEBP": ".webp"}


def encode_and_store_image(img: Image.Image) -> str:
    """Re-encode the (already validated) image, encrypt it and store it on disk.

    - The filename is generated by the server (random UUID): the client-supplied name
      is never used, so there is no path traversal, collision or overwrite issue.
    - Re-encoding with Pillow drops EXIF/metadata and any data appended to the file.
    - The bytes are encrypted with AES-256-GCM before touching the disk.
    Returns the logical name to store in Item.image_filename.
    """
    fmt = img.format.upper()
    name = f"{uuid.uuid4().hex}{FORMAT_TO_EXT[fmt]}"
    buf = io.BytesIO()
    img.save(buf, format=fmt)
    save_image(name, buf.getvalue())
    return name


